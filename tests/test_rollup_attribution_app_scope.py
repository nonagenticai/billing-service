"""``tenant_owns_licence`` used to answer "owns ANY licence, for ANY product".

THE DEFECT UNDER TEST
----------------------
``services.rollup_engine.rollup_daily`` built the boolean that feeds
``classify_cost_attribution`` (``models.db._common``) from a tenant-wide query:
``SELECT DISTINCT tenant_id FROM request_quota_config WHERE license_id !=
NULL_LICENSE_ID`` -- no ``app_id``/``service_key`` scoping at all. So a tenant
holding a licence for one product (say "Other Product") read as
``tenant_owns_licence=True`` for a licence-less cost row generated by a
COMPLETELY DIFFERENT product's ``service_key`` -- the row landed in
``ATTRIBUTION_UNLICENSED`` ("a real customer whose header was dropped") when
the tenant had never licensed the product that generated the cost at all.

Measured live 2026-09-07 against prod's ``billing_cost_daily``: naive
service_key-to-app-name string matching over-measured this at $3,354.35/$3,386.93
(99%) of the 'unlicensed' bucket. Re-measured against THIS repo's own
authoritative map (``settings.cost_attribution_app_by_service_key``, the same
one ``services.license_resolver`` already uses to attribute a licence to an
event) the real gap is far smaller -- 6 rows / $0.52 -- but it is real, and this
pins the fix: scope ``tenant_owns_licence`` to "owns a licence for the app THIS
service_key maps to", falling back to the historic tenant-wide check only when
the map does not cover the service_key at all (never fabricate a scoping
decision the map does not support -- the same rule
``services.license_resolver`` applies).

This module deliberately overrides ``cost_attribution_app_by_service_key`` to a
small, explicit test map -- see ``_scoped_map`` -- rather than depending on the
production default, so a future edit to that default cannot silently change
what this test proves.
"""

from __future__ import annotations

import uuid
from datetime import UTC, date, datetime, timedelta
from decimal import Decimal

import pytest
from sqlalchemy import insert, select

from models.db import (
    ATTRIBUTION_SYSTEM,
    ATTRIBUTION_UNLICENSED,
    CostDaily,
    CostEvent,
    RequestQuotaConfig,
)
from services.aggregator import rollup_daily
from settings import get_settings
from tests.conftest import T

_TEST_MAP = "widget-service=Widget App,gadget-service=Gadget App"


@pytest.fixture(autouse=True)
def _scoped_map(monkeypatch):
    """A small, explicit map this test owns -- not the production default."""
    monkeypatch.setenv("COST_ATTRIBUTION_APP_BY_SERVICE_KEY", _TEST_MAP)
    get_settings.cache_clear()
    yield
    get_settings.cache_clear()


def _yesterday() -> date:
    return (datetime.now(UTC) - timedelta(days=1)).date()


def _event(tenant_id: str, cost: Decimal, service_key: str) -> dict:
    return {
        "tenant_id": tenant_id,
        "tenant_name": "",
        "license_id": None,
        "service_key": service_key,
        "provider": "claude",
        "input_tokens": 100,
        "output_tokens": 50,
        "cost_usd": cost,
        "created_at": datetime(
            _yesterday().year, _yesterday().month, _yesterday().day, 12, 0, tzinfo=UTC
        ),
    }


async def _status_for(db_session_factory, tenant_id: str) -> str:
    async with db_session_factory() as session:
        return (
            await session.execute(
                select(CostDaily.attribution_status).where(CostDaily.tenant_id == tenant_id)
            )
        ).scalar_one()


class TestServiceKeyScopedOwnership:
    @pytest.mark.integration
    async def test_a_licence_for_an_unrelated_product_does_not_cover_this_call(
        self, db_session_factory
    ):
        """The core defect: owning Gadget App must not cover a Widget App call.

        Under the pre-fix tenant-wide predicate this tenant reads
        ``tenant_owns_licence=True`` (it owns SOME licence) and the row lands on
        ``unlicensed``. Scoped to the app ``widget-service`` actually maps to,
        the tenant owns nothing relevant, so the honest verdict is ``system``.
        """
        tenant = T("unrelated-product-owner")
        async with db_session_factory() as session:
            await session.execute(
                insert(RequestQuotaConfig),
                [
                    {
                        "license_id": uuid.uuid4(),
                        "tenant_id": tenant,
                        "quota_monthly": 1000,
                        "app_name": "Gadget App",
                    }
                ],
            )
            await session.execute(
                insert(CostEvent), [_event(tenant, Decimal("9.99"), "widget-service")]
            )
            await session.commit()

        await rollup_daily(db_session_factory, target_date=_yesterday())

        assert await _status_for(db_session_factory, tenant) == ATTRIBUTION_SYSTEM

    @pytest.mark.integration
    async def test_a_licence_for_the_matching_product_still_covers_it(self, db_session_factory):
        """The positive control: same shape, but the owned app is the right one."""
        tenant = T("matching-product-owner")
        async with db_session_factory() as session:
            await session.execute(
                insert(RequestQuotaConfig),
                [
                    {
                        "license_id": uuid.uuid4(),
                        "tenant_id": tenant,
                        "quota_monthly": 1000,
                        "app_name": "Widget App",
                    }
                ],
            )
            await session.execute(
                insert(CostEvent), [_event(tenant, Decimal("8.88"), "widget-service")]
            )
            await session.commit()

        await rollup_daily(db_session_factory, target_date=_yesterday())

        assert await _status_for(db_session_factory, tenant) == ATTRIBUTION_UNLICENSED

    @pytest.mark.integration
    async def test_an_unmapped_service_key_falls_back_to_the_tenant_wide_check(
        self, db_session_factory
    ):
        """Never fabricate a scoping decision the map does not support.

        `unmapped-service` is not in `_TEST_MAP`, so this predicate cannot know
        which app it belongs to -- exactly the situation
        `services.license_resolver`'s rule 1 ("never fabricate") describes for
        its own resolution. The conservative choice is the pre-existing
        tenant-wide check, not a default to `system`.
        """
        tenant = T("unmapped-service-owner")
        async with db_session_factory() as session:
            await session.execute(
                insert(RequestQuotaConfig),
                [
                    {
                        "license_id": uuid.uuid4(),
                        "tenant_id": tenant,
                        "quota_monthly": 1000,
                        "app_name": "Some Entirely Different App",
                    }
                ],
            )
            await session.execute(
                insert(CostEvent), [_event(tenant, Decimal("7.77"), "unmapped-service")]
            )
            await session.commit()

        await rollup_daily(db_session_factory, target_date=_yesterday())

        assert await _status_for(db_session_factory, tenant) == ATTRIBUTION_UNLICENSED

    @pytest.mark.integration
    async def test_owning_neither_the_right_app_nor_any_app_is_still_system(
        self, db_session_factory
    ):
        """Unaffected control: the pre-#141 case (owns nothing at all) is unchanged."""
        tenant = T("owns-nothing")
        async with db_session_factory() as session:
            await session.execute(
                insert(CostEvent), [_event(tenant, Decimal("6.66"), "widget-service")]
            )
            await session.commit()

        await rollup_daily(db_session_factory, target_date=_yesterday())

        assert await _status_for(db_session_factory, tenant) == ATTRIBUTION_SYSTEM
